import { defineRailway, github, image, preserve, project, service, volume } from "railway/iac";

// Railway Infrastructure as Code: the whole `true-ai-detective` project.
// Preview with `railway config plan`, apply with `railway config apply`.
export default defineRailway(() => {
  // Postgres + pgvector: same image as compose.yaml and the e2e tests. Data lives on the volume,
  // so it survives redeploys of the database and of every app service.
  const pgvectorVolume = volume("pgvector-volume", {
    alerts: { usage: { "100": {}, "80": {}, "95": {} } },
    allowOnlineResize: true,
    region: "europe-west4-drams3a",
    sizeMB: 5000,
  });
  const pgvector = service("pgvector", {
    source: image("pgvector/pgvector:pg18"),
    build: { buildEnvironment: "V3", builder: "RAILPACK" },
    start: '/bin/sh -c "unset PGPORT; docker-entrypoint.sh postgres --port=5432"',
    replicas: { "europe-west4-drams3a": 1 },
    // No public TCP proxy: the DB is reachable only on Railway's private network.
    networking: { tcpProxies: {} },
    volumeMounts: { "/var/lib/postgresql": pgvectorVolume },
    // Generated by the pgvector template; values stay on Railway.
    env: {
      DATABASE_URL: preserve(),
      DATABASE_URL_PRIVATE: preserve(),
      PGDATA: preserve(),
      PGDATABASE: preserve(),
      PGHOST: preserve(),
      PGHOST_PRIVATE: preserve(),
      PGPASSWORD: preserve(),
      PGPORT: preserve(),
      PGPORT_PRIVATE: preserve(),
      PGUSER: preserve(),
      POSTGRES_DB: preserve(),
      POSTGRES_PASSWORD: preserve(),
      POSTGRES_USER: preserve(),
    },
  });

  // FastAPI app, built by Railpack from this repo on every push to main.
  const api = service("api", {
    source: github("jacus/true-ai-detective", { branch: "main" }),
    start: "fastapi run src/detective/main.py",
    healthcheck: "/health",
    healthcheckTimeout: 60,
    replicas: { "europe-west4-drams3a": 1 },
    env: {
      // Fixed so the web service can reach /agent over the private network (`fastapi run` reads PORT).
      PORT: "8000",
      // Private network only: the app never talks to the DB over the public proxy.
      DATABASE_URL: pgvector.env.DATABASE_URL_PRIVATE,
      // Secret set with `railway variable set OPENAI_API_KEY --stdin --service api`; value stays on Railway.
      OPENAI_API_KEY: preserve(),
    },
  });

  // Next.js chat UI (CopilotKit), built by Railpack from web/. Its CopilotRuntime route relays
  // AG-UI to the api over Railway's private network; only the web service faces visitors.
  const web = service("web", {
    source: github("jacus/true-ai-detective", { branch: "main", rootDirectory: "web" }),
    healthcheck: "/",
    healthcheckTimeout: 60,
    replicas: { "europe-west4-drams3a": 1 },
    env: {
      // IaC refs can only be a whole value, so compose with Railway's own `${{service.VAR}}` syntax.
      DETECTIVE_AGENT_URL: "http://${{api.RAILWAY_PRIVATE_DOMAIN}}:8000/agent",
    },
  });

  return project("true-ai-detective", {
    variables: { managed: true },
    resources: [pgvector, pgvectorVolume, api, web],
  });
});
